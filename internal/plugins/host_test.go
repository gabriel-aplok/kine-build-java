func TestHostHandshake(t *testing.T) {
	jdk := requireHostJDK(t)
	root := t.TempDir()
	build := compileTestHost(t, root, jdk)

	process, bridge := startTestHost(t, jdk, root, build)
	ctx := testContext(t)

	var result handshakeResult
	if err := bridge.Call(ctx, "handshake", struct{}{}, &result); err != nil {
		t.Fatalf("handshake error = %v", err)
	}
	if result.API != APIVersion {
		t.Errorf("api = %d, want %d", result.API, APIVersion)
	}
	if len(result.Plugins) != 0 {
		t.Errorf("plugins = %d, want 0", len(result.Plugins))
	}

	stopTestHost(t, process, bridge, ctx)
}

func TestHostPluginTasks(t *testing.T) {
	jdk := requireHostJDK(t)
	root := t.TempDir()
	build := compileTestHost(t, root, jdk)
	jar := buildTestPlugin(t, jdk, build.APIJar, root, "demo", demoManifest, demoFiles)

	process, bridge := startTestHost(t, jdk, root, build, jar)
	ctx := testContext(t)

	var handshake handshakeResult
	if err := bridge.Call(ctx, "handshake", struct{}{}, &handshake); err != nil {
		t.Fatalf("handshake error = %v", err)
	}
	if len(handshake.Plugins) != 1 || handshake.Plugins[0].ID != "demo" {
		t.Fatalf("plugins = %+v", handshake.Plugins)
	}
	if len(handshake.Plugins[0].Providers) != 1 || handshake.Plugins[0].Providers[0] != "demo" {
		t.Errorf("providers = %v", handshake.Plugins[0].Providers)
	}

	projectDir := filepath.Join(root, "app")
	if err := os.MkdirAll(projectDir, 0o755); err != nil {
		t.Fatal(err)
	}
	tasks := callTasks(t, ctx, bridge, "demo", projectDir)

	generate := findTask(t, tasks, "generate")
	if generate == nil {
		t.Fatal("generate task is missing")
	}
	if len(generate.Outputs) != 1 || generate.Outputs[0].Path != "build/generated.txt" || generate.Outputs[0].Mode != "file" {
		t.Errorf("outputs = %+v", generate.Outputs)
	}
	if generate.Key != "generate" {
		t.Errorf("key = %q", generate.Key)
	}
	if findTask(t, tasks, "fail") == nil {
		t.Error("fail task is missing")
	}

	if err := bridge.Call(ctx, "run", map[string]any{
		"provider": "demo",
		"project":  "app",
		"task":     "generate",
	}, nil); err != nil {
		t.Fatalf("run generate error = %v", err)
	}
	data, err := os.ReadFile(filepath.Join(projectDir, "build", "generated.txt"))
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}
	if string(data) != "generated by plugin" {
		t.Errorf("generated = %q", data)
	}

	err = bridge.Call(ctx, "run", map[string]any{
		"provider": "demo",
		"project":  "app",
		"task":     "fail",
	}, nil)
	if err == nil {
		t.Fatal("run fail error = nil, want error")
	}
	if !strings.Contains(err.Error(), "boom") {
		t.Errorf("error %q does not contain the plugin failure", err)
	}

	stopTestHost(t, process, bridge, ctx)
}

