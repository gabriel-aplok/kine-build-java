func TestHostForwardsStderr(t *testing.T) {
	jdk := requireHostJDK(t)
	root := t.TempDir()
	build := compileTestHost(t, root, jdk)
	jar := buildTestPlugin(t, jdk, build.APIJar, root, "demo", demoManifest, demoFiles)

	stderr := &lockedBuffer{}
	host, err := NewHost(HostConfig{
		WorkspaceRoot: root,
		JDK:           jdk,
		Plugins: []Plugin{{
			Jar: jar,
			Manifest: Manifest{
				API:       APIVersion,
				ID:        "demo",
				Version:   "1.0",
				Main:      "demo.DemoPlugin",
				Providers: []string{"demo"},
			},
		}},
		Stderr: stderr,
	})
	if err != nil {
		t.Fatalf("NewHost() error = %v", err)
	}
	t.Cleanup(func() {
		host.Close()
	})

	ctx := testContext(t)
	projectDir := filepath.Join(root, "app")
	if err := os.MkdirAll(projectDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := host.Call(ctx, "tasks", map[string]any{
		"provider": "demo",
		"project": map[string]any{
			"id":      "app",
			"dir":     projectDir,
			"options": map[string]any{},
		},
	}, &tasksResult{}); err != nil {
		t.Fatalf("tasks error = %v", err)
	}
	if err := host.Call(ctx, "run", map[string]any{
		"provider": "demo",
		"project":  "app",
		"task":     "generate",
	}, nil); err != nil {
		t.Fatalf("run error = %v", err)
	}

	deadline := time.Now().Add(5 * time.Second)
	for time.Now().Before(deadline) {
		if strings.Contains(stderr.String(), "plugin noise") {
			return
		}
		time.Sleep(10 * time.Millisecond)
	}
	t.Errorf("stderr %q does not contain the plugin output", stderr.String())
}

func TestHostClassloaderIsolation(t *testing.T) {
	jdk := requireHostJDK(t)
	root := t.TempDir()
	build := compileTestHost(t, root, jdk)

	alpha := buildTestPlugin(t, jdk, build.APIJar, root, "alpha", alphaManifest, alphaFiles)
	beta := buildTestPlugin(t, jdk, build.APIJar, root, "beta", betaManifest, betaFiles)

	process, bridge := startTestHost(t, jdk, root, build, alpha, beta)
	ctx := testContext(t)

	projectDir := filepath.Join(root, "app")
	if err := os.MkdirAll(projectDir, 0o755); err != nil {
		t.Fatal(err)
	}
	callTasks(t, ctx, bridge, "alpha", projectDir)
	callTasks(t, ctx, bridge, "beta", projectDir)

	for _, name := range []string{"alpha", "beta"} {
		if err := bridge.Call(ctx, "run", map[string]any{
			"provider": name,
			"project":  "app",
			"task":     "write",
		}, nil); err != nil {
			t.Fatalf("run %s error = %v", name, err)
		}
	}

	for _, name := range []string{"alpha", "beta"} {
		data, err := os.ReadFile(filepath.Join(projectDir, "build", name+".txt"))
		if err != nil {
			t.Fatalf("read %s output: %v", name, err)
		}
		if string(data) != name {
			t.Errorf("%s output = %q, want %q", name, data, name)
		}
	}

	stopTestHost(t, process, bridge, ctx)
}

type handshakeResult struct {
	API     int `json:"api"`
	Plugins []struct {
		ID        string   `json:"id"`
		Version   string   `json:"version"`
		Providers []string `json:"providers"`
	} `json:"plugins"`
}

type pathSpec struct {
	Path string `json:"path"`
	Mode string `json:"mode"`
}

type taskDefinition struct {
	ID      string     `json:"id"`
	Deps    []string   `json:"deps"`
	Inputs  []pathSpec `json:"inputs"`
	Outputs []pathSpec `json:"outputs"`
	Key     string     `json:"key"`
}

type tasksResult struct {
	Tasks []taskDefinition `json:"tasks"`
}

func callTasks(t *testing.T, ctx context.Context, bridge *Bridge, provider, projectDir string) []taskDefinition {
	t.Helper()

	var result tasksResult
	err := bridge.Call(ctx, "tasks", map[string]any{
		"provider": provider,
		"project": map[string]any{
			"id":      "app",
			"dir":     projectDir,
			"options": map[string]any{},
		},
	}, &result)
	if err != nil {
		t.Fatalf("tasks %s error = %v", provider, err)
	}
	return result.Tasks
}

func findTask(t *testing.T, tasks []taskDefinition, id string) *taskDefinition {
	t.Helper()

	for i := range tasks {
		if tasks[i].ID == id {
			return &tasks[i]
		}
	}
	return nil
}

func compileTestHost(t *testing.T, root string, jdk *toolchain.JDK) HostBuild {
	t.Helper()

	build, err := CompileHost(context.Background(), root, jdk)
	if err != nil {
		t.Fatalf("CompileHost() error = %v", err)
	}
	return build
}

func startTestHost(t *testing.T, jdk *toolchain.JDK, root string, build HostBuild, jars ...string) (*toolchain.Process, *Bridge) {
	t.Helper()

	args := []string{"-cp", build.Classes, "dev.kine.plugin.host.Main"}
	args = append(args, jars...)
	process, err := toolchain.Start(toolchain.Command{
		Path: jdk.Java,
		Args: args,
		Dir:  root,
		Env:  toolchain.BuildEnv(jdk, root, nil),
	})
	if err != nil {
		t.Fatalf("Start() error = %v", err)
	}

	bridge := NewBridge(process.Stdout(), process.Stdin(), nil)
	t.Cleanup(func() {
		bridge.Close()
		process.Kill()
	})
	return process, bridge
}

func stopTestHost(t *testing.T, process *toolchain.Process, bridge *Bridge, ctx context.Context) {
	t.Helper()

	if err := bridge.Call(ctx, "shutdown", struct{}{}, nil); err != nil {
		t.Fatalf("shutdown error = %v", err)
	}
	if err := process.Wait(); err != nil {
		t.Errorf("Wait() error = %v", err)
	}
}

func testContext(t *testing.T) context.Context {
	t.Helper()

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	t.Cleanup(cancel)
	return ctx
}

func buildTestPlugin(t *testing.T, jdk *toolchain.JDK, apiJar, workspace, name, manifest string, files map[string]string) string {
	t.Helper()

	base := t.TempDir()
	sourceDir := filepath.Join(base, "src")
	classDir := filepath.Join(base, "classes")

	names := make([]string, 0, len(files))
	for path, content := range files {
		names = append(names, path)
		if err := os.MkdirAll(filepath.Join(sourceDir, filepath.Dir(filepath.FromSlash(path))), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(sourceDir, filepath.FromSlash(path)), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	sort.Strings(names)

	args := []string{"--release", "17", "-cp", apiJar, "-d", classDir}
	for _, path := range names {
		args = append(args, filepath.Join(sourceDir, filepath.FromSlash(path)))
	}
	result, err := toolchain.Run(context.Background(), toolchain.Command{
		Path: jdk.Javac,
		Args: args,
		Dir:  base,
		Env:  toolchain.BuildEnv(jdk, base, nil),
	})
	if err != nil {
		t.Fatalf("javac %s: %v\n%s", name, err, result.Stderr)
	}

	jarPath := filepath.Join(workspace, "plugins", name+".jar")
	writePluginJar(t, jarPath, manifest, classDir)
	return jarPath
}

func writePluginJar(t *testing.T, path, manifest, classDir string) {
	t.Helper()

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	file, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	writer := zip.NewWriter(file)

	entry, err := writer.Create(manifestPath)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := entry.Write([]byte(manifest)); err != nil {
		t.Fatal(err)
	}

	err = filepath.WalkDir(classDir, func(filePath string, item os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if item.IsDir() {
			return nil
		}
		name, err := filepath.Rel(classDir, filePath)
		if err != nil {
			return err
		}
		entry, err := writer.Create(filepath.ToSlash(name))
		if err != nil {
			return err
		}
		data, err := os.ReadFile(filePath)
		if err != nil {
			return err
		}
		_, err = entry.Write(data)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	if err := writer.Close(); err != nil {
		t.Fatal(err)
	}
	if err := file.Close(); err != nil {
		t.Fatal(err)
	}
}

