const r8RulesVersion = 1

const defaultR8Rules = `# Generated by Kine. Keep Android entry points, native methods, and custom views.
-keep class * extends android.app.Activity { *; }
-keep class * extends android.app.Application { *; }
-keep class * extends android.app.Service { *; }
-keep class * extends android.content.BroadcastReceiver { *; }
-keep class * extends android.content.ContentProvider { *; }
-keep class * extends android.view.View { <init>(...); }
-keepclasseswithmembernames,includedescriptorclasses class * {
    native <methods>;
}
-keepclassmembers class * { @android.webkit.JavascriptInterface <methods>; }
`

func (p *Provider) runR8(ctx context.Context, project *core.Project, options Options, sdk *SDK, jdk *toolchain.JDK, artifacts []deps.Artifact, classesJar, output string) error {
	if sdk.R8Jar == "" {
		return fmt.Errorf("R8 jar is missing from build-tools %s", sdk.BuildTools)
	}
	rules, err := p.writeR8Rules(project, options)
	if err != nil {
		return err
	}
	mappingDir := filepath.Join(project.Dir, "build", "outputs", "mapping", options.variantLabel())
	if err := os.MkdirAll(mappingDir, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", mappingDir, err)
	}

	jars, err := classpathJars(artifacts, filepath.Join(project.Dir, "build", "android", "aar"))
	if err != nil {
		return err
	}
	if options.KotlinStdlib != "" {
		jars = append(jars, options.KotlinStdlib)
	}

	args := []string{
		"-cp", sdk.R8Jar,
		"com.android.tools.r8.R8",
		"--release",
		"--min-api", fmt.Sprintf("%d", options.MinSDK),
		"--lib", sdk.AndroidJar,
		"--output", output,
		"--pg-conf", rules,
		"--pg-map-output", filepath.Join(mappingDir, "mapping.txt"),
	}
	for _, jar := range jars {
		args = append(args, "--classpath", jar)
	}
	args = append(args, classesJar)

	tmpDir := filepath.Join(project.Dir, ".kine", "tmp")
	if err := os.MkdirAll(tmpDir, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", tmpDir, err)
	}
	result, err := p.run(ctx, toolchain.Command{
		Path: jdk.Java,
		Args: args,
		Dir:  project.Dir,
		Env:  toolchain.BuildEnv(jdk, tmpDir, nil),
	})
	if err != nil {
		return toolError("r8", result, err)
	}
	return nil
}

func (p *Provider) writeR8Rules(project *core.Project, options Options) (string, error) {
	dir := options.androidPath(project.Dir, "r8")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("create %s: %w", dir, err)
	}

	var buffer strings.Builder
	buffer.WriteString(defaultR8Rules)
	buffer.WriteString("\n")

	manifestPath := options.androidPath(project.Dir, "AndroidManifest.xml")
	if merged, err := parseManifest(manifestPath); err == nil {
		application := findManifestChild(merged, "application")
		if application != nil {
			for _, child := range application.Children {
				if child.Name.Local != "activity" && child.Name.Local != "service" &&
					child.Name.Local != "receiver" && child.Name.Local != "provider" {
					continue
				}
				name := attributeValue(child, "android", "name")
				if name == "" {
					continue
				}
				if strings.HasPrefix(name, ".") {
					name = attributeValue(merged, "", "package") + name
				}
				buffer.WriteString("-keep class " + name + " { *; }\n")
			}
		}
	}

	rules := append([]string(nil), options.Variant.BuildTypeOptions.Proguard...)
	rules = append(rules, options.AARProguard...)
	for _, rule := range rules {
		data, err := os.ReadFile(rule)
		if err != nil {
			return "", fmt.Errorf("read proguard rules %s: %w", rule, err)
		}
		buffer.WriteString("\n# " + filepath.Base(rule) + "\n")
		buffer.Write(data)
		if !strings.HasSuffix(string(data), "\n") {
			buffer.WriteByte('\n')
		}
	}

	target := filepath.Join(dir, "rules.pro")
	if err := os.WriteFile(target, []byte(buffer.String()), 0o644); err != nil {
		return "", fmt.Errorf("write %s: %w", target, err)
	}
	return target, nil
}

func r8Inputs(workspaceRoot string, project *core.Project, options Options) []core.Input {
	var inputs []core.Input
	for _, path := range append(append([]string(nil), options.Variant.BuildTypeOptions.Proguard...), options.AARProguard...) {
		if relative, err := relativePath(workspaceRoot, path); err == nil {
			inputs = append(inputs, core.Input{Path: relative, Mode: core.ModeFile})
		}
	}
	manifest := options.androidPath(project.Dir, "AndroidManifest.xml")
	if relative, err := relativePath(workspaceRoot, manifest); err == nil {
		inputs = append(inputs, core.Input{Path: relative, Mode: core.ModeFile})
	}
	sort.Slice(inputs, func(i, j int) bool { return inputs[i].Path < inputs[j].Path })
	return inputs
}
